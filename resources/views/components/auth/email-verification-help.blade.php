    <h2 class="mb-2 font-semibold text-gray-900 dark:text-white">Belum menerima email verifikasi?</h2>
    <ol class="list-decimal space-y-2 pl-5">
        <li>Buka aplikasi email Anda, lalu periksa <strong>Kotak Masuk (Inbox)</strong>.</li>
        <li>Jika belum ditemukan, buka folder <strong>Spam, Junk, atau Email Sampah</strong>.</li>
        <li>Untuk pengguna Gmail, periksa juga tab <strong>Promosi</strong> dan <strong>Sosial</strong>.</li>
        <li>Coba gunakan fitur pencarian pada aplikasi email dengan kata <strong>verifikasi</strong> atau nama portal pendaftaran.</li>
        <li>Jika pesan ada di Spam, buka pesan tersebut dan pilih <strong>Bukan spam</strong> agar pesan berikutnya lebih mudah ditemukan.</li>
        <li>Jika masih belum ada, pastikan Anda memakai alamat email yang benar lalu klik <strong>Kirim Ulang Email Verifikasi</strong> di halaman ini. Tunggu sebentar sebelum mencoba lagi.</li>
    </ol>
    <p class="mt-3 text-xs text-gray-600 dark:text-gray-300">
        Demi keamanan, jangan pernah membagikan tautan verifikasi atau kode rahasia kepada orang lain.
    </p>
